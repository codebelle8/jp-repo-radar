import assert from "node:assert/strict";
import { afterEach, beforeEach, describe, it } from "node:test";
import { createCompany } from "../lib/companies.js";
import { FIX_REVISION } from "../lib/fix-agent.js";
import {
  cancelFix, createFix, createPullRequest, evaluatePrecheck, getFix, postReply, prActivity, refreshBySession, refreshFix,
  respondToReview, setupFixAgent, setupStatus, watchFixes,
} from "../lib/fixes.js";
import { listNotifications, markRead, notify, unreadCount } from "../lib/notifications.js";
import { trackerView } from "../lib/tracker.js";
import { FakeAnthropic, FakeGitHub, tempStore } from "./helpers.mjs";

const noSleep = async () => {};
const NOW = Date.parse("2026-11-27T00:00:00Z");
const day = (n) => new Date(NOW - n * 864e5).toISOString();

function issueRepo(o = {}) {
  return {
    nameWithOwner: "acme/web", url: "https://github.com/acme/web", isArchived: !!o.archived, stargazerCount: 120,
    defaultBranchRef: { name: "main" }, primaryLanguage: { name: o.lang || "TypeScript" }, licenseInfo: o.noLicense ? null : { spdxId: "MIT", name: "MIT" },
    contributingGuidelines: { body: o.contributing ?? "Run npm test before sending a pull request.", url: "https://github.com/acme/web/blob/main/CONTRIBUTING.md" },
    aiPolicy: o.aiPolicy ? { text: o.aiPolicy } : null, aiPolicyGithub: null,
    issue: o.noIssue ? null : {
      number: 12, title: "Login button does nothing on Safari", body: o.body || "Steps: open /login in Safari and click the button.", state: o.state || "OPEN",
      url: "https://github.com/acme/web/issues/12", createdAt: day(20), author: { login: "reporter" },
      assignees: { nodes: (o.assignees || []).map((login) => ({ login })) }, labels: { nodes: [{ name: "good first issue" }] },
      comments: { totalCount: (o.comments || []).length, nodes: o.comments || [] },
      closedByPullRequestsReferences: { nodes: o.openPr ? [{ url: "https://github.com/acme/web/pull/9", state: "OPEN" }] : [] },
    },
  };
}

describe("auto-fix pre-check", () => {
  it("blocks closed, assigned or already-fixed issues and warns about claims, licenses, macOS and AI rules", () => {
    const ok = evaluatePrecheck({ repository: issueRepo() }, { viewer: "codebelle8", now: NOW });
    assert.deepEqual([ok.problems, ok.warnings], [[], []]);
    const bad = evaluatePrecheck({ repository: issueRepo({ state: "CLOSED", assignees: ["someone"], openPr: true, archived: true }) }, { viewer: "codebelle8", now: NOW });
    assert.deepEqual(bad.problems.map((p) => p.text), ["The repository is archived.", "The issue is already closed.", "The issue is assigned to {who}.",
      "A pull request that closes this issue is already open: {url}"]);
    assert.equal(bad.problems[2].vars.who, "@someone");
    assert.equal(evaluatePrecheck({ repository: issueRepo({ assignees: ["CodeBelle8"] }) }, { viewer: "codebelle8", now: NOW }).problems.length, 0, "assigned to you is fine");
    const warn = evaluatePrecheck({ repository: issueRepo({ lang: "Swift", noLicense: true, comments: [{ author: { login: "dev" }, body: "I'm working on this", createdAt: day(3) }],
      aiPolicy: "We do not accept pull requests generated by AI tools. Thanks!" }) }, { viewer: "codebelle8", now: NOW });
    assert.equal(warn.warnings.length, 4);
    assert.deepEqual(warn.mentions, [{ source: "AI_POLICY.md", excerpt: "We do not accept pull requests generated by AI tools." }]);
    assert.equal(evaluatePrecheck({ repository: issueRepo({ comments: [{ author: { login: "dev" }, body: "やります", createdAt: day(60) }] }) }, { now: NOW }).warnings.length, 0, "old claims are ignored");
    assert.equal(evaluatePrecheck({ repository: null }).problems[0].text, "Repository not found.");
    assert.match(evaluatePrecheck({ repository: issueRepo({ noIssue: true }) }).problems[0].text, /Issue not found/);
  });

  it("sorts pull request activity and marks your own", () => {
    const items = prActivity({
      reviews: { nodes: [{ id: "r1", author: { login: "maint" }, state: "CHANGES_REQUESTED", body: "Please add a test", submittedAt: day(1), url: "u1" }, { id: "r0", state: "PENDING", submittedAt: day(1) }] },
      comments: { nodes: [{ id: "c1", author: { login: "codebelle8" }, body: "Thanks", createdAt: day(0.5), url: "u2" }] },
      reviewThreads: { nodes: [{ comments: { nodes: [{ id: "t1", author: { login: "maint" }, body: "nit", createdAt: day(2), path: "src/a.ts", url: "u3" }] } }] },
    }, "CodeBelle8");
    assert.deepEqual(items.map((i) => [i.id, i.kind, i.mine]), [["t1", "review comment", false], ["r1", "review", false], ["c1", "comment", true]]);
  });
});

describe("auto-fix flow", () => {
  let store, gh, ai, acme, branches, prs, comments, prData;
  const env = {};
  beforeEach(async () => {
    for (const k of ["ANTHROPIC_API_KEY", "GITHUB_WRITE_TOKEN", "FIX_BUDGET_CENTS"]) env[k] = process.env[k];
    process.env.ANTHROPIC_API_KEY = "sk-test";
    process.env.GITHUB_WRITE_TOKEN = "ghp-write";
    delete process.env.FIX_BUDGET_CENTS;
    store = tempStore();
    gh = new FakeGitHub();
    ai = new FakeAnthropic();
    acme = await createCompany(store, { name: "Acme", orgs: ["acme"] });
    branches = { main: 1 };   // value: how many 404s before the branch appears (forking is asynchronous)
    prs = [];
    comments = [];
    prData = null;
    let repo = issueRepo();
    gh.setRepo = (r) => { repo = r; };
    gh.onGraphql("query FixPrecheck", () => ({ repository: repo }));
    gh.onGraphql("query FixPr", () => ({ repository: { pullRequest: prData } }));
    gh.onRest("GET", /^\/user$/, () => [200, { login: "codebelle8", id: 218400670, name: null }]);
    gh.onRest("POST", /^\/repos\/acme\/web\/forks$/, () => [202, { full_name: "codebelle8/web", name: "web", owner: { login: "codebelle8" }, html_url: "https://github.com/codebelle8/web" }]);
    gh.onRest("GET", /^\/repos\/codebelle8\/web\/branches\/(.+)$/, (m) => {
      const name = decodeURIComponent(m[1]);
      if (!(name in branches)) return [404];
      if (branches[name] > 0) { branches[name]--; return [404]; }
      return [200, { name }];
    });
    gh.onRest("POST", /^\/repos\/codebelle8\/web\/merge-upstream$/, () => [200, { merge_type: "fast-forward" }]);
    gh.onRest("GET", /^\/repos\/acme\/web\/compare\/(.+)$/, () => [200, { ahead_by: 2, html_url: "https://github.com/acme/web/compare/main...codebelle8:fix/issue-12",
      files: [{ filename: "src/login.ts", status: "modified", additions: 3, deletions: 1, patch: "@@ -1 +1 @@\n-old\n+new" }, { filename: "test/login.test.ts", status: "added", additions: 20, deletions: 0, patch: "+test" }] }]);
    gh.onRest("POST", /^\/repos\/acme\/web\/pulls$/, (m, body) => { prs.push(body); return [201, { number: 31, html_url: "https://github.com/acme/web/pull/31" }]; });
    gh.onRest("POST", /^\/repos\/acme\/web\/issues\/31\/comments$/, (m, body) => { comments.push(body); return [201, { id: 5, node_id: "IC_mine" }]; });
  });
  afterEach(() => {
    for (const [k, v] of Object.entries(env)) { if (v === undefined) delete process.env[k]; else process.env[k] = v; }
    store.cleanup();
  });
  const deps = () => ({ anthropic: ai, fetchImpl: gh.fetch, sleepImpl: noSleep });
  const fixed = (extra = {}) => ({ status: "fixed", reason: "", summary_ja: "Safari でボタンが反応しない問題を修正しました。", explanation_ja: "## 原因\n...",
    tests: { commands: ["npm test"], passed: true, output_tail: "42 passing" }, branch: "fix/issue-12", commit_shas: ["abc"],
    pr_title: "Fix login button on Safari", pr_body: "Fixes #12\n\nThe click handler ...", ai_disclosure_required: false, reply: "", ...extra });

  it("sets up the agent once and updates it when the definition changes", async () => {
    assert.equal((await setupStatus(store)).ready, false);
    const first = await setupFixAgent(store, deps());
    assert.deepEqual([first.agentId, first.environmentId, first.revision], ["agent_1", "env_1", FIX_REVISION]);
    await setupFixAgent(store, deps());
    assert.deepEqual(ai.agents.map(([op]) => op), ["create"], "no change: nothing to update");
    await store.set("fixAgent", { ...first, revision: "old" });
    await setupFixAgent(store, deps());
    assert.deepEqual(ai.agents.map(([op]) => op), ["create", "update"]);
    assert.equal((await setupStatus(store)).ready, true);
    const agent = ai.agents[0][1];
    assert.equal(agent.model.id, "claude-opus-5-5");
    assert.deepEqual(agent.tools[0].configs.map((c) => [c.name, c.enabled]), [["web_fetch", false], ["web_search", false]]);
  });

  it("runs the whole flow: pre-check, fork, session, result, pull request, reviews, reply, merge", async () => {
    await assert.rejects(createFix(store, { url: "https://github.com/acme/web/issues/12" }, deps()), /setup first/);
    await setupFixAgent(store, deps());
    await assert.rejects(createFix(store, { url: "https://github.com/acme/web/pull/3" }, deps()), /pull request/);

    let fix = await createFix(store, { url: "https://github.com/acme/web/issues/12" }, deps());
    assert.equal(fix.status, "running");
    assert.deepEqual([fix.fork.fullName, fix.fork.branch, fix.companyId], ["codebelle8/web", "fix/issue-12", acme.id]);
    const params = ai.created[0];
    assert.deepEqual(params.agent, { type: "agent", id: "agent_1", version: 1 });
    assert.deepEqual(params.resources.map((r) => [r.type, r.mount_path]), [["github_repository", "/workspace/repo"], ["file", "/workspace/issue.md"]]);
    assert.equal(params.resources[0].url, "https://github.com/codebelle8/web");
    assert.deepEqual(params.initial_events.map((e) => e.type), ["user.message", "user.define_outcome"]);
    assert.deepEqual(params.budget, { type: "limit", max_list_cost: { amount: "500", currency: "USD" } });
    const kickoff = params.initial_events[0].content[0].text;
    assert.match(kickoff, /codebelle8 <218400670\+codebelle8@users\.noreply\.github\.com>/);
    assert.ok(!kickoff.includes("open /login in Safari"), "issue text is mounted as a file, not sent as the owner's message");
    assert.match(ai.uploads[0].text, /open \/login in Safari/);
    await assert.rejects(createFix(store, { url: "https://github.com/acme/web/issues/12" }, deps()), /already has an auto-fix/);

    // still running: cost is tracked
    ai.sessions.sesn_1.usage.list_cost.amount = "35";
    fix = await refreshFix(store, fix, deps());
    assert.deepEqual([fix.status, fix.session.costCents], ["running", 35]);
    // a call the platform could not judge: declined, the agent continues
    Object.assign(ai.sessions.sesn_1, { status: "idle", events: [{ type: "session.status_idle", stop_reason: { type: "requires_action", event_ids: ["sevt_9"] } }] });
    fix = await refreshFix(store, fix, deps());
    assert.equal(fix.status, "running");
    assert.deepEqual(ai.sent[0].events, [{ type: "user.tool_confirmation", tool_use_id: "sevt_9", result: "deny" }]);
    // done: result file, branch and diff
    ai.finish("sesn_1", fixed());
    branches["fix/issue-12"] = 0;
    fix = await refreshBySession(store, "sesn_1", deps());
    assert.equal(fix.status, "ready");
    assert.deepEqual([fix.result.tests.passed, fix.result.outcome, fix.diff.commits, fix.diff.files.length, fix.session.costCents], [true, "satisfied", 2, 2, 180]);
    let n = await listNotifications(store);
    assert.deepEqual(n.items.map((i) => [i.type, i.vars.issue]), [["fix_ready", "acme/web#12"]]);

    // pull request (your approval step)
    fix = await createPullRequest(store, fix.id, { title: "Fix login button on Safari", body: "The click handler ..." }, deps());
    assert.equal(fix.status, "pr_open");
    assert.deepEqual([prs[0].head, prs[0].base, prs[0].maintainer_can_modify], ["codebelle8:fix/issue-12", "main", true]);
    assert.match(prs[0].body, /^Fixes #12\n/);
    assert.equal((await trackerView(store)).items[0].url, "https://github.com/acme/web/issues/12", "added to the tracker");

    // reviews, comments and CI arrive
    prData = { state: "OPEN", merged: false, url: fix.pr.url, reviewDecision: "CHANGES_REQUESTED",
      reviews: { nodes: [{ id: "r1", author: { login: "maint" }, state: "CHANGES_REQUESTED", body: "Please add a Safari note to the README", submittedAt: day(0.2), url: "x" }] },
      comments: { nodes: [{ id: "c0", author: { login: "codebelle8" }, body: "Ready for review", createdAt: day(0.3), url: "y" }] },
      reviewThreads: { nodes: [] }, commits: { nodes: [{ commit: { oid: "abc", statusCheckRollup: { state: "FAILURE" } } }] } };
    let w = await watchFixes(store, deps());
    assert.deepEqual([w.watched, w.notifications], [1, 2]);
    n = await listNotifications(store);
    assert.deepEqual(n.items.slice(0, 2).map((i) => i.type).sort(), ["ci_failed", "review"]);
    w = await watchFixes(store, deps());
    assert.equal(w.notifications, 0, "nothing new: no repeat notifications");

    // respond to the review in a new session on the same branch
    fix = await respondToReview(store, fix.id, deps());
    assert.deepEqual([fix.status, fix.phase], ["running", "review"]);
    assert.deepEqual(ai.created[1].resources[0].checkout, { type: "branch", name: "fix/issue-12" });
    assert.match(ai.uploads[1].text, /Please add a Safari note/);
    ai.finish("sesn_2", fixed({ reply: "README に Safari の注意書きを追加しました。" }));
    fix = await refreshFix(store, fix, deps());
    assert.equal(fix.status, "reply_ready");
    fix = await postReply(store, fix.id, { body: fix.reviewResult.reply }, deps());
    assert.deepEqual([fix.status, comments[0].body], ["pr_open", "README に Safari の注意書きを追加しました。"]);
    await assert.rejects(respondToReview(store, fix.id, deps()), /no new review comments/);

    // merged
    prData = { ...prData, state: "MERGED", merged: true, commits: { nodes: [{ commit: { oid: "def", statusCheckRollup: { state: "SUCCESS" } } }] } };
    await watchFixes(store, deps());
    fix = await getFix(store, fix.id);
    assert.equal(fix.status, "merged");
    n = await listNotifications(store);
    assert.equal(n.items[0].type, "merged");
    assert.deepEqual(n.items.map((i) => i.type).sort(), ["ci_failed", "fix_ready", "merged", "reply_ready", "review"]);
  });

  it("limits pull requests to one per company per day", async () => {
    await setupFixAgent(store, deps());
    const base = { issue: { owner: "acme", repo: "web", number: 1, url: "https://github.com/acme/web/issues/1", title: "x" }, companyId: acme.id,
      fork: { owner: "codebelle8", branch: "fix/issue-1", fullName: "codebelle8/web" }, precheck: { defaultBranch: "main" }, history: [] };
    await store.hset("fixes", { "acme:web:1": { ...base, id: "acme:web:1", status: "pr_open", pr: { number: 2, createdAt: new Date().toISOString() } },
      "acme:web:2": { ...base, id: "acme:web:2", status: "ready", result: { prTitle: "t", prBody: "Closes #2" } } });
    await assert.rejects(createPullRequest(store, "acme:web:2", {}, deps()), /last 24 hours/);
  });

  it("stops at the pre-check, the spending cap, or when you cancel", async () => {
    await setupFixAgent(store, deps());
    gh.setRepo(issueRepo({ openPr: true }));
    let fix = await createFix(store, { url: "https://github.com/acme/web/issues/12" }, deps());
    assert.equal(fix.status, "blocked");
    assert.equal(ai.created.length, 0, "no session for a blocked issue");
    assert.ok(!gh.restCalls.some((c) => c.path.endsWith("/forks")), "and no fork");

    gh.setRepo(issueRepo());
    fix = await createFix(store, { url: "https://github.com/acme/web/issues/12" }, deps());
    assert.deepEqual([fix.status, fix.attempt], ["running", 2]);
    Object.assign(ai.sessions.sesn_1, { status: "idle", events: [{ type: "session.status_idle", stop_reason: { type: "budget_reached" } }] });
    fix = await refreshFix(store, fix, deps());
    assert.deepEqual([fix.status, fix.error.vars.amount], ["failed", "5.00"]);
    assert.equal((await listNotifications(store)).items[0].type, "fix_failed");

    branches["fix/issue-12"] = 0;   // a branch from the failed attempt is left alone; the next attempt gets a new name
    fix = await createFix(store, { url: "https://github.com/acme/web/issues/12" }, deps());
    assert.equal(fix.fork.branch, "fix/issue-12-2");
    fix = await cancelFix(store, fix.id, deps());
    assert.equal(fix.status, "cancelled");
    assert.deepEqual(ai.sent.at(-1).events, [{ type: "user.interrupt" }]);
  });

  it("reports tests that fail and agents that stop", async () => {
    await setupFixAgent(store, deps());
    let fix = await createFix(store, { url: "https://github.com/acme/web/issues/12" }, deps());
    ai.finish("sesn_1", fixed({ tests: { commands: ["npm test"], passed: false, output_tail: "1 failing" } }));
    branches["fix/issue-12"] = 0;
    fix = await refreshFix(store, fix, deps());
    assert.equal(fix.status, "needs_attention");
    await assert.rejects(createPullRequest(store, fix.id, {}, deps()), /not ready/);

    fix = await createFix(store, { url: "https://github.com/acme/web/issues/12" }, deps());
    ai.finish("sesn_2", { status: "blocked", reason: "CONTRIBUTING で AI による貢献が禁止されています。" });
    fix = await refreshFix(store, fix, deps());
    assert.deepEqual([fix.status, fix.result.reason], ["blocked", "CONTRIBUTING で AI による貢献が禁止されています。"]);
  });
});

describe("notifications", () => {
  let store;
  beforeEach(() => { store = tempStore(); });
  afterEach(() => store.cleanup());

  it("stores, counts and marks notifications as read", async () => {
    const a = await notify(store, { type: "review", title: "New review on {issue}: {state}", vars: { issue: "a/b#1", state: "APPROVED" }, link: "/fixes/x" });
    await notify(store, { type: "merged", title: "Merged: {issue}", vars: { issue: "a/b#1" } });
    assert.equal(await unreadCount(store), 2);
    await markRead(store, []);
    assert.equal(await unreadCount(store), 2, "an empty list marks nothing");
    await markRead(store, [a.id, "missing"]);
    assert.equal(await unreadCount(store), 1);
    await markRead(store, "all");
    const list = await listNotifications(store);
    assert.deepEqual([list.unread, list.total, list.items[0].type], [0, 2, "merged"]);
  });
});
